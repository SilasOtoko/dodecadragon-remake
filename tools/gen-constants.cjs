// Generates src/engine/constants.ts and src/content/text.ts from the original scripts/constants.js.
// Gameplay data goes to the engine; names and descriptions (which contain the original's HTML)
// go to content for the UI.  usage: node tools/gen-constants.cjs reference/original
const fs = require('fs');
const path = require('path');
const orig = process.argv[2];
const src = fs.readFileSync(path.join(orig, 'scripts/constants.js'), 'utf8');
// Real top-level declarations only (the file also has some inside comments).
const names = require('@babel/parser').parse(src).program.body
  .filter((n) => n.type === 'VariableDeclaration').flatMap((n) => n.declarations.map((d) => d.id.name));
const values = new Function(`${src}; return { ${names.join(', ')} };`)();

const TEXT = new Set(['romanNumerals', 'hellLayerNames', 'hellLayerEffects', 'hypergodNames', 'hypergodText',
  'nuclearPastaNames', 'nuclearPastaPositiveEffects', 'nuclearPastaNegativeEffects', 'achievementNames',
  'achievementRewards', 'achievementColours', 'sigilResetterModesFull']);
const SKIP = new Set(['panResistantFields', 'tabData']); // map/panning UI of the original
const header = (what) => `// GENERATED by tools/gen-constants.cjs from reference/original/scripts/constants.js. Do not edit by hand.\n// ${what}\n\n`;
const emit = (n) => `export const ${n} = ${JSON.stringify(values[n], null, 1).replace(/\n\s*/g, ' ')} as const;\n`;
const unknown = names.filter((n) => !TEXT.has(n) && !SKIP.has(n));
fs.mkdirSync('src/content', { recursive: true });
fs.writeFileSync('src/engine/constants.ts', header('Gameplay data: costs, scaling bases, achievement thresholds and visibility.') + unknown.map(emit).join('\n'));
fs.writeFileSync('src/content/text.ts', header("Display text. Strings keep the original's inline HTML (colour tags, &#8202; spacing); the UI decides how to render them.") + [...TEXT].map(emit).join('\n'));
console.log('engine:', unknown.join(', '));
