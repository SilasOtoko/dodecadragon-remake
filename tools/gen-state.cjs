// Generates src/engine/state.ts and docs/save-fields.md from tools/reset-fields.json.
const fs = require('fs');
const [,, jsonPath, tsOut, mdOut] = process.argv;
const SYSTEMS = [
  ['Meta and settings', /^(unlockedAchievements|unlocks|lastMajorChangeVersion|lastUpdate|lastSave|lastSigilReset|timePlayed|backgroundPatternOn|confirmations|achievementFlashActive|currentTab|dragonName)$/],
  ['Sigil automation', /^sigilResetter/],
  ['Gold and miners', /^(gold|goldPerSecond|miners|minerCost|goldPerClick|minerAutoBuyMax)$/],
  ['Dragon', /^dragon/],
  ['Fire', /^fire/],
  ['Alchemy I: platinum', /^(platinum|bestPlatinum)/],
  ['Magic and magic upgrades', /^(magic(ToGet|Effect|UpgradesBought)?|darkMagicUpgradesBought|voidMagicUpgradesBought)$/],
  ['Magic challenges', /^(selectedChallenges|challengesActive|noOfSelectedChallenges|magicScore|magifolds)/],
  ['Alchemy II: uranium', /^(uranium|bestUranium)/],
  ['Sigils: cyan to pink', /^(cyan|blue|indigo|violet|pink)Sigil/],
  ['Knowledge', /^(knowledge|highestKnowledge)/],
  ['Tomes', /^(tome|totalTomes)/],
  ['Blue fire', /^blueFire/],
  ['Blood and hell', /^(blood|bloodPerSecond|currentHellLayer|inHell)$/],
  ['Alchemy III: plutonium', /^(plutonium|bestPlutonium)/],
  ['Sigils: red, orange, yellow', /^(red|orange|yellow)Sigil/],
  ['Holy polyhedrons', /^holy(Tetra|Octa|Dodeca)/],
  ['Holy fire', /^holyFire/],
  ['Planets and hypergods', /^(planet|supercluster|hypergods)/],
  ['Cosmic plague', /^(cosmicPlague|spore|plague)/],
  ['Alchemy IV: oganesson', /^oganesson/],
  ['Essences', /^(light|dark|death|finality)Essence/],
  ['Nuclear pasta', /^nuclearPasta/],
  ['Finality cubes', /^finality(Cube|Boost)/],
];
const raw = require(require('path').resolve(jsonPath)).map((f) => {
  const sys = SYSTEMS.find(([, rx]) => rx.test(f.key));
  if (!sys) throw new Error(`No system for field ${f.key}: add it to SYSTEMS in gen-state.cjs`);
  return { ...f, section: sys[0], note: f.note.startsWith('I still need') ? '' : f.note };
});
// Group by system (stable). Key order doesn't affect save compatibility: load matches by name.
const order = SYSTEMS.map(([name]) => name);
const fields = [...raw].sort((a, b) => order.indexOf(a.section) - order.indexOf(b.section));
// Element types for arrays whose default doesn't reveal them (empty, or reassigned at runtime).
const arrayOverride = {
  magicUpgradesBought: 'boolean', darkMagicUpgradesBought: 'boolean', voidMagicUpgradesBought: 'boolean',
  tomeUpgradesBought: 'boolean', holyTetrahedronUpgradesBought: 'boolean', holyOctahedronUpgradesBought: 'boolean',
  holyDodecahedronUpgradesBought: 'boolean',
  knowledgeTrade1Multipliers: 'Decimal | number', knowledgeTrade2Multipliers: 'Decimal | number', knowledgeTrade3Multipliers: 'Decimal | number',
};
const tsType = (f) => {
  if (f.t === 'Decimal') return 'Decimal';
  if (f.t === 'array') {
    if (arrayOverride[f.key]) return `(${arrayOverride[f.key]})[]`;
    const ts = [...new Set(f.v.map(e => e.t === 'Decimal' ? 'Decimal' : e.t))];
    return ts.length === 1 ? `${ts[0]}[]` : `(${ts.join(' | ')})[]`;
  }
  return f.t;
};
const tsVal = (f) => {
  if (f.t === 'Decimal') return `new Decimal(${JSON.stringify(f.v)})`;
  if (f.t === 'array') return `[${f.v.map(e => tsVal(e)).join(', ')}]`;
  return JSON.stringify(f.v);
};
const isTime = (k) => ['lastUpdate', 'lastSigilReset'].includes(k);
let sec = null, iface = '', init = '';
for (const f of fields) {
  if (f.section !== sec) { sec = f.section; if (sec) { iface += `\n  // ${sec}\n`; init += `\n    // ${sec}\n`; } }
  const note = f.note ? ` // ${f.note}` : '';
  iface += `  ${f.key}: ${tsType(f)};${note}\n`;
  init += `    ${f.key}: ${isTime(f.key) ? 'now' : tsVal(f)},\n`;
}
const ts = `// GENERATED by tools/gen-state.cjs from the original reset() in scripts/script.js. Do not edit by hand.
// Field names, types and defaults match DodecaDragons v1.0.1 so saves stay compatible.
import Decimal from '../vendor/break_eternity.js';

export interface GameState {${iface}}

/** A loaded save: known fields plus any legacy keys older versions left behind (kept on re-export). */
export type SaveData = GameState & Record<string, unknown>;

/** Equivalent of the original reset(): a brand-new game. */
export function createInitialState(now: number = Date.now()): GameState {
  return {${init}  };
}

export const FIELD_COUNT = ${fields.length};
`;
fs.writeFileSync(tsOut, ts);
// Markdown reference
const fmt = (f) => f.t === 'array' ? '[' + f.v.map(e => e.t === 'Decimal' ? e.v : JSON.stringify(e.v)).join(', ') + ']' : f.t === 'Decimal' ? f.v : JSON.stringify(f.v);
let md = `# Save fields (generated)\n\nAll ${fields.length} fields of the \`game\` object, in the order the original \`reset()\` declares them, with their new-game defaults. Generated by \`tools/gen-state.cjs\`; the typed version is \`src/engine/state.ts\`.\n\n"Decimal" values are break_eternity numbers, stored in saves as strings.\n`;
sec = null;
for (const f of fields) {
  if (f.section !== sec) { sec = f.section; md += `\n## ${sec || 'General'}\n\n| Field | Type | Default | Note |\n|---|---|---|---|\n`; }
  md += `| \`${f.key}\` | ${tsType(f).replace(/\|/g, '\\|')} | \`${isTime(f.key) ? 'Date.now()' : fmt(f)}\` | ${f.note.replace(/\|/g, '\\|')} |\n`;
}
fs.writeFileSync(mdOut, md);
console.log('wrote', tsOut, mdOut);
